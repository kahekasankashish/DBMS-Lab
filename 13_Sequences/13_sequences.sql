-- Q8. Display sequence properties and the current/next values for all sequences visible to the current user.
SELECT
    schemaname,
    sequencename,
    start_value,
    increment_by,
    min_value,
    max_value,
    cycle,
    last_value AS current_value,
    CASE
        WHEN last_value IS NULL THEN start_value
        WHEN increment_by > 0 AND last_value + increment_by > max_value
             THEN CASE WHEN cycle THEN min_value ELSE NULL END
        WHEN increment_by < 0 AND last_value + increment_by < min_value
             THEN CASE WHEN cycle THEN max_value ELSE NULL END
        ELSE last_value + increment_by
    END AS next_value_if_called
FROM pg_sequences
WHERE schemaname = current_schema()
ORDER BY sequencename;

