-- Q1. Create sqnum: increment 3, start/minimum -9, maximum 9999,
--     no cycling and no ordering.
CREATE SEQUENCE sqnum
    START WITH -9
    INCREMENT BY 3
    MINVALUE -9
    MAXVALUE 9999
    NO CYCLE;

-- Q2. The DOCX repeats the same sqnum definition in a second question.
